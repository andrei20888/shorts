#!/usr/bin/env node
// Measure public/audio/vo/line_NN.mp3 durations (speech only) → src/config/voTiming.ts
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'public', 'audio', 'vo');
const files = fs.readdirSync(dir).filter((f) => /^line_\d+\.mp3$/.test(f)).sort();
const out = files.map((f) => {
  const log = execFileSync('ffmpeg', ['-hide_banner', '-i', path.join(dir, f), '-af', 'silencedetect=n=-40dB:d=0.25', '-f', 'null', '-'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).toString();
  return log;
});
const durs = files.map((f, i) => {
  const r = execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', path.join(dir, f)], { encoding: 'utf8' });
  let d = Number(r.trim());
  // trim trailing silence reported by silencedetect
  const m = [...(out[i] || '').matchAll(/silence_start: ([\d.]+)/g)].map((x) => Number(x[1]));
  const last = m.length ? m[m.length - 1] : null;
  if (last && last > d * 0.5) d = last;
  return +d.toFixed(2);
});
fs.writeFileSync(path.join(root, 'src', 'config', 'voTiming.ts'), `/** Seconds each VO line lasts (generated by scripts/vo-timing.mjs from public/audio/vo/). */\nexport const VO_DURATIONS: number[] = ${JSON.stringify(durs)};\n`);
console.log('✓ voTiming.ts', durs.length, 'lines');
