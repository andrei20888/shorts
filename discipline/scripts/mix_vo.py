#!/usr/bin/env python3
"""
Voice-over prep + per-line music ducking.

  python3 scripts/mix_vo.py

1. Keeps the untouched Higgsfield/ElevenLabs takes in audio_src/vo_raw/ (copied once).
2. Processes each line into public/audio/vo/line_NN.mp3: high-pass, presence lift,
   gentle compression, gain to TARGET_LUFS, peak limit.
3. Measures the score under every line (out/score.wav; file t=0 = film 3.0 s) and writes
   src/config/voDuck.ts: how many dB the music dips under each line so the voice sits
   ~HEADROOM_LU above it.

Needs: ffmpeg, numpy, soundfile, pyloudnorm (pip install soundfile pyloudnorm).
Line start times + durations come from `npx tsx` evaluating timing.ts + voTiming.ts.
"""
import io
import json
import os
import shutil
import subprocess

import numpy as np
import pyloudnorm as pyln
import soundfile as sf

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VO_DIR = os.path.join(ROOT, 'public/audio/vo')
RAW_DIR = os.path.join(ROOT, 'audio_src/vo_raw')
SCORE = os.path.join(ROOT, 'out/score.wav')
OUT_TS = os.path.join(ROOT, 'src/config/voDuck.ts')
MUSIC_OFFSET = 3.0  # film seconds at score t=0 (MUSIC.start)

TARGET_LUFS = -15.0
HEADROOM_LU = 6.0
DUCK_MIN, DUCK_MAX = 3.0, 10.0
MUSIC_GAIN_DB = -5.0  # must match MUSIC.gainDb in timing.ts

CHAIN = ','.join([
    'highpass=f=85',
    'equalizer=f=220:t=q:w=1.0:g=-1.5',
    'equalizer=f=3200:t=q:w=1.0:g=2.5',
    'acompressor=threshold=-22dB:ratio=3:attack=6:release=90:knee=4',
])


def lines():
    js = ("import { VO_LINES, FPS } from './src/timing';"
          "import { VO_DURATIONS } from './src/config/voTiming';"
          "console.log(JSON.stringify(VO_LINES.map((l, i) => [l.at / FPS, VO_DURATIONS[i]])));")
    out = subprocess.run(['npx', 'tsx', '-e', js], cwd=ROOT, capture_output=True, text=True, check=True).stdout
    return json.loads(out.strip().splitlines()[-1])


def decode(path, extra=None):
    cmd = ['ffmpeg', '-v', 'error', '-i', path]
    if extra:
        cmd += ['-af', extra]
    cmd += ['-ar', '44100', '-f', 'wav', '-']
    data, sr = sf.read(io.BytesIO(subprocess.run(cmd, capture_output=True, check=True).stdout))
    return data, sr


def loud(meter_sr, x):
    dur = len(x) / meter_sr
    return pyln.Meter(meter_sr, block_size=min(0.4, dur * 0.9)).integrated_loudness(x)


def main():
    os.makedirs(RAW_DIR, exist_ok=True)
    data = lines()
    music, msr = sf.read(SCORE)
    duck = []
    for i, (at, dur) in enumerate(data):
        name = f'line_{i + 1:02d}.mp3'
        raw = os.path.join(RAW_DIR, name)
        if not os.path.exists(raw):
            shutil.copy(os.path.join(VO_DIR, name), raw)

        x, sr = decode(raw, CHAIN)  # always from the raw take → re-running is idempotent
        g = TARGET_LUFS - loud(sr, x)
        y = x * 10 ** (g / 20)
        peak = np.max(np.abs(y))
        lim = 10 ** (-2.0 / 20)
        if peak > lim:  # soft-knee peak limiter (speech peaks are short)
            y = np.tanh(y / lim) * lim
        wav = io.BytesIO()
        sf.write(wav, y, sr, format='WAV', subtype='FLOAT')
        subprocess.run(['ffmpeg', '-v', 'error', '-y', '-f', 'wav', '-i', '-', '-c:a', 'libmp3lame', '-b:a', '192k',
                        os.path.join(VO_DIR, name)], input=wav.getvalue(), check=True)

        a = int((at - MUSIC_OFFSET) * msr)
        b = int((at - MUSIC_OFFSET + max(dur, 0.6)) * msr)
        ml = (loud(msr, music[a:b]) if a >= 0 else -70.0) + MUSIC_GAIN_DB
        need = ml - (TARGET_LUFS - HEADROOM_LU) if np.isfinite(ml) else 0.0
        d = float(np.clip(need, DUCK_MIN, DUCK_MAX))
        duck.append(round(d, 1))
        print(f'{name}  gain {g:+5.1f} dB  peak {20 * np.log10(peak + 1e-9):5.1f} dBFS  music {ml:6.1f} LUFS  duck {d:4.1f} dB')

    with open(OUT_TS, 'w') as f:
        f.write('// Generated by scripts/mix_vo.py — dB the music dips under each VO line (index = VO_LINES index).\n')
        f.write(f'export const VO_DUCK_DB: number[] = {json.dumps(duck)};\n')
    print(f'✓ {OUT_TS}')


if __name__ == '__main__':
    main()
